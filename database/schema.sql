CREATE TABLE exception_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  event_id CHAR(36) NOT NULL UNIQUE,
  occurred_at DATETIME(6) NOT NULL,
  reported_at DATETIME(6) NOT NULL,
  project_code VARCHAR(64) NOT NULL,
  repository_code VARCHAR(128) NOT NULL,
  instance_code VARCHAR(64) NOT NULL,
  environment VARCHAR(32) NOT NULL,
  service VARCHAR(128) NOT NULL,
  category VARCHAR(32) NOT NULL,
  exception_type VARCHAR(160) NOT NULL,
  severity VARCHAR(8) NOT NULL,
  fingerprint CHAR(64) NOT NULL,
  summary VARCHAR(1000) NOT NULL,
  exception_class VARCHAR(255) NULL,
  operation VARCHAR(255) NULL,
  entity_type VARCHAR(64) NULL,
  entity_id VARCHAR(128) NULL,
  request_id VARCHAR(128) NULL,
  trace_id VARCHAR(128) NULL,
  source_version VARCHAR(128) NULL,
  source_host VARCHAR(255) NULL,
  source_url VARCHAR(2000) NULL,
  context_json JSON NULL,
  stack_trace TEXT NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  INDEX exception_events_scope (project_code,instance_code,environment,occurred_at),
  INDEX exception_events_fingerprint (fingerprint,occurred_at),
  INDEX exception_events_type (exception_type,occurred_at),
  INDEX exception_events_reported (reported_at)
);
